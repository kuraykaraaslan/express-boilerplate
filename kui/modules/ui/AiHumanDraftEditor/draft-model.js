/*
 * modules/ui/AiHumanDraftEditor/draft-model.js
 *
 * The pure part of AiHumanDraftEditor: a port of kui-react modules/ui/AiHumanDraftEditor/diff.ts (the word-level
 * diff, hunks, applying a choice per hunk), the default messages, the summary text of a hunk, and the class
 * strings of the component (what kui-react's cn() / tailwind-merge resolves them to, written out once so the
 * server partial and the browser view cannot drift). No DOM, no dependencies. One source for both sides: the
 * partial loads it on the server through _observability/_load.ejs, and the browser scripts inline it first.
 * Exposed as window.KuiDraftModel (and module.exports under Node).
 *
 * Words and whitespace runs are separate tokens, so applying a hunk never glues words together or loses spacing.
 * Prefix and suffix are trimmed before the LCS table; a middle too large for a table (over MAX_CELLS) becomes a
 * single replace hunk instead of freezing the page.
 */
(function (global) {
  'use strict';
  if (global.KuiDraftModel) return;

  var MAX_CELLS = 4000000;

  var DEFAULT_MESSAGES = {
    aiBadge: 'AI-generated',
    aiBadgeModel: 'AI-generated by {model}',
    aiPanel: 'AI draft',
    humanPanel: 'Your text',
    edit: 'Edit text',
    review: 'Review changes',
    editorLabel: 'Your text',
    accept: 'Accept',
    reject: 'Reject',
    acceptAll: 'Accept all',
    keepMine: 'Keep mine',
    reconsider: 'Reconsider',
    pending: '{count} changes pending',
    noPending: 'No changes pending',
    identical: 'Your text matches the AI draft.',
    changeLabel: 'Change {index} of {total}',
    acceptAria: 'Accept change {index}: {summary}',
    rejectAria: 'Reject change {index}: {summary}',
    reconsiderAria: 'Reconsider rejected change {index}: {summary}',
    replace: 'replace “{human}” with “{ai}”',
    insert: 'insert “{ai}”',
    remove: 'remove “{human}”',
    nothing: '(nothing)',
    removed: '(removed)',
    rejected: 'rejected',
    acceptedAnnounce: 'Accepted change {index}.',
    rejectedAnnounce: 'Rejected change {index}.',
    allAcceptedAnnounce: 'All pending changes accepted.',
    allRejectedAnnounce: 'All pending changes rejected. Your text is unchanged.'
  };

  /** The defaults with the given overrides on top (a null or undefined override keeps the default). */
  function mergeMessages(overrides) {
    var out = {};
    var o = overrides && typeof overrides === 'object' ? overrides : {};
    Object.keys(DEFAULT_MESSAGES).forEach(function (k) { out[k] = o[k] != null ? String(o[k]) : DEFAULT_MESSAGES[k]; });
    return out;
  }

  /** Replace `{name}` placeholders in a message template. Unknown placeholders are left in place. */
  function fillMessage(template, values) {
    return String(template).replace(/\{(\w+)\}/g, function (whole, key) {
      return Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : whole;
    });
  }

  /** Split into words and whitespace runs: `"a  b"` -> `["a", "  ", "b"]`. */
  function tokenize(text) {
    return String(text).match(/\s+|\S+/g) || [];
  }

  function diffTokens(a, b) {
    var start = 0;
    while (start < a.length && start < b.length && a[start] === b[start]) start++;
    var endA = a.length;
    var endB = b.length;
    while (endA > start && endB > start && a[endA - 1] === b[endB - 1]) { endA--; endB--; }
    var ops = [];
    var i, j, t;
    for (i = 0; i < start; i++) ops.push({ type: 'equal', text: a[i] });

    var midA = a.slice(start, endA);
    var midB = b.slice(start, endB);
    var n = midA.length;
    var m = midB.length;
    if (n === 0) {
      for (j = 0; j < m; j++) ops.push({ type: 'insert', text: midB[j] });
    } else if (m === 0) {
      for (i = 0; i < n; i++) ops.push({ type: 'delete', text: midA[i] });
    } else if (n * m > MAX_CELLS) {
      for (i = 0; i < n; i++) ops.push({ type: 'delete', text: midA[i] });
      for (j = 0; j < m; j++) ops.push({ type: 'insert', text: midB[j] });
    } else {
      // LCS lengths from the end, so the walk below runs forward and prefers deletions before insertions.
      var w = m + 1;
      var table = new Uint32Array((n + 1) * w);
      for (i = n - 1; i >= 0; i--) {
        for (j = m - 1; j >= 0; j--) {
          table[i * w + j] = midA[i] === midB[j]
            ? table[(i + 1) * w + j + 1] + 1
            : Math.max(table[(i + 1) * w + j], table[i * w + j + 1]);
        }
      }
      i = 0; j = 0;
      while (i < n && j < m) {
        if (midA[i] === midB[j]) { ops.push({ type: 'equal', text: midA[i] }); i++; j++; }
        else if (table[(i + 1) * w + j] >= table[i * w + j + 1]) { ops.push({ type: 'delete', text: midA[i] }); i++; }
        else { ops.push({ type: 'insert', text: midB[j] }); j++; }
      }
      while (i < n) { ops.push({ type: 'delete', text: midA[i++] }); }
      while (j < m) { ops.push({ type: 'insert', text: midB[j++] }); }
    }
    for (t = endA; t < a.length; t++) ops.push({ type: 'equal', text: a[t] });
    return ops;
  }

  /**
   * Segments of the diff between the human's text and the AI's: unchanged text `{ type: 'equal', text }` and hunks
   * `{ type: 'hunk', hunk: { key, human, ai } }` (a run of deletions and insertions, glued across whitespace-only
   * gaps). A hunk's key is stable across re-diffs of the same change: its content plus its occurrence number.
   */
  function buildSegments(human, ai) {
    human = human == null ? '' : String(human);
    ai = ai == null ? '' : String(ai);
    if (human === ai) return human ? [{ type: 'equal', text: human }] : [];
    var ops = diffTokens(tokenize(human), tokenize(ai));

    var raw = [];
    ops.forEach(function (op) {
      var last = raw[raw.length - 1];
      if (op.type === 'equal') {
        if (last && last.type === 'equal') last.text += op.text; else raw.push({ type: 'equal', text: op.text });
      } else {
        var target = last && last.type === 'change' ? last : (raw.push({ type: 'change', human: '', ai: '' }), raw[raw.length - 1]);
        if (op.type === 'delete') target.human += op.text; else target.ai += op.text;
      }
    });
    // Glue change - whitespace - change into one change, so a rewritten phrase is one hunk.
    var glued = [];
    for (var i = 0; i < raw.length; i++) {
      var cur = raw[i];
      var prev = glued[glued.length - 1];
      if (cur.type === 'equal' && /^\s+$/.test(cur.text) && prev && prev.type === 'change' && raw[i + 1] && raw[i + 1].type === 'change') {
        var next = raw[i + 1];
        prev.human += cur.text + next.human;
        prev.ai += cur.text + next.ai;
        i++;
      } else if (cur.type === 'change' && prev && prev.type === 'change') {
        prev.human += cur.human;
        prev.ai += cur.ai;
      } else {
        glued.push(cur.type === 'change' ? { type: 'change', human: cur.human, ai: cur.ai } : cur);
      }
    }

    var seen = Object.create(null);
    return glued.map(function (s) {
      if (s.type === 'equal') return s;
      var base = s.human + '\u0000' + s.ai;
      var nth = seen[base] || 0;
      seen[base] = nth + 1;
      return { type: 'hunk', hunk: { key: base + '#' + nth, human: s.human, ai: s.ai } };
    });
  }

  /** The text with every hunk resolved by `choose(hunk)`: 'ai' takes the draft's side, 'human' keeps the person's. */
  function applySegments(segments, choose) {
    return segments.map(function (s) { return s.type === 'equal' ? s.text : choose(s.hunk) === 'ai' ? s.hunk.ai : s.hunk.human; }).join('');
  }

  /** The hunks only, in order. */
  function hunksOf(segments) {
    var out = [];
    segments.forEach(function (s) { if (s.type === 'hunk') out.push(s.hunk); });
    return out;
  }

  /** What the component draws for a pair of texts and a set of rejected keys: segments, hunks, numbering, pending. */
  function derive(value, aiDraft, rejectedKeys) {
    var rejected = Object.create(null);
    (rejectedKeys || []).forEach(function (k) { rejected[k] = true; });
    var segments = buildSegments(value, aiDraft);
    var hunks = hunksOf(segments);
    var indexOf = Object.create(null);
    hunks.forEach(function (h, i) { indexOf[h.key] = i + 1; });
    var pending = hunks.filter(function (h) { return !rejected[h.key]; });
    return {
      segments: segments, hunks: hunks, pending: pending,
      indexOf: function (h) { return indexOf[h.key] || 0; },
      isRejected: function (h) { return rejected[h.key] === true; }
    };
  }

  /** Screen-reader summary of a hunk: replace, insert or remove. */
  function summary(msg, h) {
    return h.human && h.ai ? fillMessage(msg.replace, { human: h.human.trim(), ai: h.ai.trim() })
      : h.ai ? fillMessage(msg.insert, { ai: h.ai.trim() })
        : fillMessage(msg.remove, { human: h.human.trim() });
  }

  var FOCUS = 'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-border-focus';
  var GHOST_BASE = 'inline-flex items-center rounded border px-2 py-1 text-xs font-medium transition-colors disabled:cursor-not-allowed disabled:opacity-50 ' + FOCUS;
  var CHIP = 'inline-flex items-center gap-1 rounded border bg-surface-base px-1.5 text-[11px] font-medium leading-5 transition-colors hover:bg-surface-overlay ' + FOCUS;

  /**
   * The class strings, as kui-react's cn() resolves them (tailwind-merge drops the base class a later one
   * overrides). Functions take the state the class depends on.
   */
  var CLASSES = {
    root: 'flex flex-col gap-3',
    grid: 'grid gap-3 md:grid-cols-2',
    panel: 'flex min-w-0 flex-col rounded-md border border-border bg-surface-raised',
    panelHeader: 'flex flex-wrap items-center justify-between gap-2 border-b border-border px-3 py-2',
    panelTitle: 'text-sm font-semibold text-text-primary',
    badge: 'inline-flex items-center gap-1.5 rounded-full border border-secondary bg-surface-base px-2 py-0.5 text-xs font-medium text-secondary',
    badgeIcon: 'h-3 w-3',
    body: 'whitespace-pre-wrap break-words p-3 text-sm leading-6 text-text-primary',
    textarea: 'w-full flex-1 resize-y rounded-b-md bg-surface-base p-3 text-sm leading-6 text-text-primary ' + FOCUS,
    editButtonIcon: 'me-1.5 h-3 w-3',
    num: 'mx-0.5 rounded bg-surface-sunken px-1 text-[10px] font-semibold text-text-secondary',
    emptySide: 'not-italic text-text-secondary',
    humanStrike: 'line-through decoration-error decoration-2',
    rejectedNote: 'ms-1 text-xs text-text-secondary',
    chips: 'ms-1 inline-flex gap-1 align-baseline',
    chipIcon: 'h-2.5 w-2.5',
    footer: 'flex flex-wrap items-center gap-2',
    pending: 'text-sm text-text-secondary',
    footerButtons: 'ms-auto flex gap-2',
    footerIcon: 'me-1.5 h-3 w-3',
    status: 'sr-only',
    ghost: GHOST_BASE + ' border-border bg-surface-base text-text-primary hover:bg-surface-overlay',
    ghostOn: GHOST_BASE + ' hover:bg-surface-overlay border-primary bg-primary-subtle text-primary',
    primary: GHOST_BASE + ' border-primary bg-primary text-primary-fg hover:bg-primary-hover',
    chipReconsider: CHIP,
    chipAccept: CHIP + ' border-success text-success-fg',
    chipReject: CHIP + ' border-error text-error-fg',
    aiHunk: function (rejected, active) {
      var base = 'rounded-sm underline decoration-2 underline-offset-2';
      if (rejected) return base + ' text-text-disabled decoration-border' + (active ? ' bg-secondary/25' : '');
      return base + (active ? ' bg-secondary/25 decoration-secondary' : ' bg-secondary/10 decoration-secondary');
    },
    humanHunk: function (rejected, active) {
      return 'rounded-sm ' + (rejected ? 'opacity-60' + (active ? ' bg-error-subtle' : '') : (active ? 'bg-error-subtle' : 'bg-error-subtle/60'));
    }
  };

  var api = {
    MAX_CELLS: MAX_CELLS, DEFAULT_MESSAGES: DEFAULT_MESSAGES, CLASSES: CLASSES,
    mergeMessages: mergeMessages, fillMessage: fillMessage, tokenize: tokenize, buildSegments: buildSegments,
    applySegments: applySegments, hunksOf: hunksOf, derive: derive, summary: summary
  };
  global.KuiDraftModel = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
