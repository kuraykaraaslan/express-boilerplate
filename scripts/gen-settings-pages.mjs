#!/usr/bin/env node
// Generates pages/settings.manifest.ts: one entry per core module settings page that NB builds on ModuleSettingsPage
// (tenant_setting/ui/module-settings-page.component.tsx), keyed by the page's componentId from module.json `routes`.
// The pages are uniform (title, subtitle, parent crumb, fields list, moduleId), so ONE data-driven Express page serves them all.
// Pages with extras around the settings form (tabs, owner-only lock, other panels) are listed with `extras: true`:
// the settings form is served, the extras are not (yet).
// Usage: node scripts/gen-settings-pages.mjs [path-to-nb]
import fs from 'node:fs';
import path from 'node:path';

const nb = path.resolve(process.argv[2] || (process.env.NEXT_BOILERPLATE_ROOT ?? '/home/kuray/next-boilerplate'));
const out = path.resolve(import.meta.dirname, '../pages/settings.manifest.ts');
const modulesDir = path.join(nb, 'modules');

// A t('key', 'Fallback') call or a plain string literal, returns the English text.
function text(expr) {
  if (!expr) return '';
  const m = expr.match(/t\(\s*'[^']*'\s*,\s*(['"`])((?:\\.|(?!\1).)*)\1/s) || expr.match(/^\s*(['"`])((?:\\.|(?!\1).)*)\1\s*$/s);
  return m ? m[2].replace(/\\(['"`\\])/g, '$1') : '';
}
// The value of one JSX prop of the block: prop={...} (balanced) or prop="...".
function prop(block, name) {
  const i = block.search(new RegExp(`\\b${name}=`));
  if (i < 0) return null;
  let j = i + name.length + 1;
  if (block[j] === '"') return block.slice(j + 1, block.indexOf('"', j + 1));
  if (block[j] !== '{') return null;
  let depth = 0, k = j;
  for (; k < block.length; k++) {
    if (block[k] === '{') depth++;
    else if (block[k] === '}' && --depth === 0) break;
  }
  return block.slice(j + 1, k);
}

const entries = [];
const skipped = [];
for (const id of fs.readdirSync(modulesDir).sort()) {
  const mj = path.join(modulesDir, id, 'module.json');
  if (!fs.existsSync(mj)) continue;
  const m = JSON.parse(fs.readFileSync(mj, 'utf8'));
  if (m.edition !== 'core') continue;
  for (const r of m.routes ?? []) {
    const file = path.join(modulesDir, `${r.component}.tsx`);
    if (!fs.existsSync(file)) continue;
    const src = fs.readFileSync(file, 'utf8');
    const start = src.indexOf('<ModuleSettingsPage');
    if (start < 0) continue;
    const block = src.slice(start, src.indexOf('/>', start));
    const fields = (prop(block, 'fields') ?? '').trim();
    const imp = src.match(new RegExp(`import\\s*\\{[^}]*\\b${fields}\\b[^}]*\\}\\s*from\\s*'([^']+)'`));
    if (!fields || !imp) { skipped.push(`${id} ${r.path}: fields not resolvable`); continue; }
    const crumb = prop(block, 'parentCrumb') ?? '';
    const crumbLabel = text((crumb.match(/label:\s*(t\((?:[^()]|\([^)]*\))*\)|'[^']*'|"[^"]*")/) || [])[1]);
    const crumbHref = ((crumb.match(/tenantPath\([^,]+,\s*'([^']*)'/) || [])[1]) ?? '/admin';
    const wrapped = /<TabGroup|<fieldset|OWNER_ONLY|<Panel|<[A-Z][A-Za-z]*Panel\b/.test(src);
    entries.push({
      componentId: r.component, path: r.path, moduleId: prop(block, 'moduleId') ?? id,
      title: text(prop(block, 'title')), subtitle: text(prop(block, 'subtitle')),
      crumbLabel, crumbHref, fields, from: imp[1], extras: wrapped,
      permissions: r.permissions ?? [],
    });
  }
}

const importLines = [...new Set(entries.map((e) => `import { ${e.fields} } from '${e.from}';`))].sort();
const body = entries.map((e) => `  ${JSON.stringify(e.componentId)}: {
    moduleId: ${JSON.stringify(e.moduleId)}, path: ${JSON.stringify(e.path)},
    title: ${JSON.stringify(e.title)}, subtitle: ${JSON.stringify(e.subtitle)},
    crumb: { label: ${JSON.stringify(e.crumbLabel)}, href: ${JSON.stringify(e.crumbHref)} },
    fields: ${e.fields}${e.extras ? ',\n    extras: true' : ''},
  },`).join('\n');

fs.writeFileSync(out, `// GENERATED by scripts/gen-settings-pages.mjs from NB's ModuleSettingsPage pages. Do not edit.
import type { SettingFieldDef } from '@kuraykaraaslan-labs/tenant_setting/server/setting-fields.types';
${importLines.join('\n')}

export type SettingsPageDef = {
  moduleId: string;
  path: string;
  title: string;
  subtitle: string;
  crumb: { label: string; href: string };
  fields: SettingFieldDef[];
  /** NB wraps the form in more (tabs, an owner-only lock, other panels); only the form is served here. */
  extras?: boolean;
};

export const settingsPages: Record<string, SettingsPageDef> = {
${body}
};
`);
console.log(`${entries.length} settings pages written to ${path.relative(process.cwd(), out)}`);
for (const s of skipped) console.log('skipped:', s);
console.log('with extras:', entries.filter((e) => e.extras).map((e) => e.moduleId).join(', '));
