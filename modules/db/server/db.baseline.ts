/**
 * Pure rules of the baseline migration: the one SQL file that builds the whole entity schema, so a database in `migrate`
 * mode can start from nothing (every other migration file alters tables it expects to exist). No fs, no database, no
 * env: the generator (`modules/db/scripts/db-baseline.ts`), the deploy runner and the tests share these definitions.
 *
 * The baseline is `db:000_baseline.sql`. It is generated, not written: `modules/db/scripts/db-baseline.ts` asks TypeORM for the
 * DDL `synchronize` would run against an empty scratch schema and renders it here. It always runs FIRST (the loader in
 * db.migration-files.ts pins it), and exactly once per database:
 *
 *   - an empty database runs it as any other migration;
 *   - a database that `synchronize` already built never runs it: the sync pass that just ran IS the baseline, so the
 *     deploy records it in the ledger without executing it (`record`);
 *   - a database that has tables but was never synchronized by this run (a node that used to run migrations over an old
 *     schema, a dedicated tenant database) is refused until `db:baseline -- --adopt` has done the one last sync pass.
 *
 * A baseline that was released must never be regenerated: its checksum is in every ledger, so an edit fails closed.
 * Schema changes after it are ordinary migration files, and `db:schema:drift` fails CI when an entity changed without one.
 */

import { stripScratchSchema } from './db.schema-drift';

export const BASELINE_MODULE_ID = 'db';
export const BASELINE_FILE = '000_baseline.sql';
/** Ledger identity of the baseline: `<module>:<file>`. */
export const BASELINE_NAME = `${BASELINE_MODULE_ID}:${BASELINE_FILE}`;
/** Repo-relative path of the committed baseline. */
export const BASELINE_PATH = `modules/${BASELINE_MODULE_ID}/server/migrations/${BASELINE_FILE}`;

/** Extensions the entity DDL depends on, found by what its statements use (TypeORM installs them on connect, not in the log). */
const EXTENSIONS: ReadonlyArray<{ name: string; pattern: RegExp }> = [
  { name: 'uuid-ossp', pattern: /\buuid_generate_v4\s*\(/ },
  { name: 'citext', pattern: /\bcitext\b/ },
  { name: 'hstore', pattern: /\bhstore\b/ },
  { name: 'ltree', pattern: /\bltree\b/ },
];

/** Names of the extensions the statements need, in a stable order. */
export function requiredExtensions(statements: ReadonlyArray<string>): string[] {
  return EXTENSIONS.filter(({ pattern }) => statements.some((s) => pattern.test(s))).map(({ name }) => name);
}

const HEADER = `-- kind: expand; reversible: false
-- db 000: the baseline. The complete schema TypeORM builds from the entities, as of the day this file was generated.
--
-- GENERATED by \`npm run db:baseline\` (modules/db/scripts/db-baseline.ts). Do not edit it by hand and do not regenerate it once a
-- release carries it: its checksum is recorded in every database ledger, so an edited copy fails closed. Schema changes
-- after the baseline are ordinary migration files; \`npm run db:schema:drift\` fails CI when an entity changed without one.
--
-- It runs first and exactly once. An empty database runs it; a database \`synchronize\` already built records it without
-- running it; any other database with tables is adopted first (\`npm run db:baseline -- --adopt\`).
`;

/**
 * The text of the baseline file for DDL that was rendered in the scratch schema `schema`. The first statement puts
 * `public` after the target schema on the search path for this transaction only, so `uuid_generate_v4()` resolves
 * while every object is still created in the target schema. Extensions are installed in `public`, where TypeORM's own
 * `synchronize` puts them, so a migrated database and a synchronized one print the same column defaults.
 */
export function renderBaselineSql(statements: ReadonlyArray<string>, schema: string): string {
  if (statements.length === 0) throw new Error('[db-baseline] there are no statements to snapshot (no entities?)');
  const body = stripScratchSchema(statements, schema);
  const lines = [
    "SELECT set_config('search_path', quote_ident(current_schema()) || ', public', true);",
    ...requiredExtensions(body).map((name) => `CREATE EXTENSION IF NOT EXISTS "${name}" SCHEMA public;`),
    ...body.map((s) => `${s.trimEnd().replace(/;+$/, '')};`),
  ];
  return `${HEADER}\n${lines.join('\n')}\n`;
}

export type BaselineAction =
  /** The baseline is not pending: nothing to do. */
  | 'none'
  /** Execute the file (empty database). */
  | 'run'
  /** Write the ledger row without executing the file (a sync pass just built the schema). */
  | 'record'
  /** The database has tables and nobody synchronized it: needs `db:baseline -- --adopt`. */
  | 'refuse';

/**
 * What to do with the baseline in this deploy run.
 *
 * @param pending       the baseline has no ledger row
 * @param synchronized  a `synchronize` pass ran in this very run, so the schema is the entity schema
 * @param hasTables     the target already holds tables besides the bookkeeping ones (`_sql_migrations`, `_schema_state`)
 */
export function decideBaselineAction(input: { pending: boolean; synchronized: boolean; hasTables: boolean }): BaselineAction {
  if (!input.pending) return 'none';
  if (input.synchronized) return 'record';
  return input.hasTables ? 'refuse' : 'run';
}

