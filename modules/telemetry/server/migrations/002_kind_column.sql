-- kind: expand
-- telemetry 002: the kind column (docs/phases/42-telemetry/00 ED-10, 02 §2.0).
--
--   telemetry_kinds             kind name → small id, platform reference data (no tenant rows; RLS-exempt by design).
--   <raw>.kindId, <1m>.kindId   a plain smallint column, in no key and no index: a query adds `kindId = $k`, so an id of another kind
--                               returns nothing; a kind can be purged or counted. 2 bytes per ~350-byte raw row (0.6 %), nothing on the
--                               primary-key B-tree every insert probes (a key member would cost +8 bytes per index tuple, MAXALIGN).
--   telemetry_latest.kindId     replaces entityType (one place for one fact; the name comes back through the registry).
--
-- Existing rows: every raw and minute row of an IoT-era install is a device's, so the column is added with the CONSTANT default 1
-- (`iot_device`, seeded below with that id) — Postgres records a constant default in the catalog without rewriting the table (also
-- on a hypertable's chunks), then the default is dropped so a new row must carry its kind. The latest table is small (entities × keys)
-- and is updated from its entityType. The bookkeeping tables carry FORCE RLS: a deploy login that is not a superuser needs the admin
-- bypass for the UPDATE, set inside the block.

CREATE TABLE IF NOT EXISTS "telemetry_kinds" (
  "kindId"    smallint GENERATED BY DEFAULT AS IDENTITY,
  "kind"      varchar(64) NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "telemetry_kinds_pkey" PRIMARY KEY ("kindId"),
  CONSTRAINT "uq_telemetry_kinds_kind" UNIQUE ("kind")
);
INSERT INTO "telemetry_kinds" ("kindId", "kind") VALUES (1, 'iot_device') ON CONFLICT DO NOTHING;
SELECT setval(pg_get_serial_sequence('"telemetry_kinds"', 'kindId'), GREATEST((SELECT max("kindId") FROM "telemetry_kinds"), 1));

DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['app_runtime', 'app_admin'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('GRANT SELECT, INSERT ON "telemetry_kinds" TO %I', r);
      EXECUTE format('GRANT USAGE ON SEQUENCE "telemetry_kinds_kindId_seq" TO %I', r);
    END IF;
  END LOOP;
END $$;

DO $$
DECLARE
  d int;
  t text;
BEGIN
  FOREACH d IN ARRAY ARRAY[7, 30, 90, 365, 1095] LOOP
    FOREACH t IN ARRAY ARRAY['telemetry_msg_r' || d, 'telemetry_1m_r' || d] LOOP
      IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = t AND column_name = 'kindId') THEN
        EXECUTE format('ALTER TABLE %I ADD COLUMN "kindId" smallint NOT NULL DEFAULT 1', t);
        EXECUTE format('ALTER TABLE %I ALTER COLUMN "kindId" DROP DEFAULT', t);
      END IF;
    END LOOP;
  END LOOP;

  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'telemetry_latest' AND column_name = 'kindId') THEN
    PERFORM set_config('app.bypass_rls', 'on', true);
    ALTER TABLE "telemetry_latest" ADD COLUMN "kindId" smallint;
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'telemetry_latest' AND column_name = 'entityType') THEN
      INSERT INTO "telemetry_kinds" ("kind") SELECT DISTINCT "entityType" FROM "telemetry_latest" WHERE "entityType" IS NOT NULL ON CONFLICT DO NOTHING;
      UPDATE "telemetry_latest" l SET "kindId" = k."kindId" FROM "telemetry_kinds" k WHERE l."kindId" IS NULL AND k."kind" = l."entityType";
      ALTER TABLE "telemetry_latest" DROP COLUMN "entityType";
    END IF;
    UPDATE "telemetry_latest" SET "kindId" = 1 WHERE "kindId" IS NULL;
    ALTER TABLE "telemetry_latest" ALTER COLUMN "kindId" SET NOT NULL;
  END IF;
END $$;
